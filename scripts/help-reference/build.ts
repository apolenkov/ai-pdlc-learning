import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

import { escapeHtml, renderSiteNavigation } from '../site-navigation-contract.ts';
import { helpReferenceCatalog, validateHelpReferenceCatalog } from './catalog.ts';
import { roleSchemaPanels, roleTeamPanels } from './role-panels.ts';
import type {
  HelpReferenceCatalog,
  ReferenceGlossaryGroup,
  ReferenceRole,
  ReferenceSource,
} from './types.ts';

const pages = resolve(import.meta.dirname, '../../docs/pages/sdlc-development');

const termCount = (count: number): string => {
  const mod100 = count % 100;
  const mod10 = count % 10;
  const noun =
    mod100 >= 11 && mod100 <= 14
      ? 'терминов'
      : mod10 === 1
        ? 'термин'
        : mod10 >= 2 && mod10 <= 4
          ? 'термина'
          : 'терминов';
  return `${count} ${noun}`;
};

const referenceDocument = (
  title: string,
  description: string,
  body: string,
): string => `<!doctype html>
<!-- GENERATED by npm run help:build (scripts/help-reference/). Do not edit by hand. -->
<html lang="ru" data-atmos data-section="help">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="${escapeHtml(description)}">
  <meta name="theme-color" content="#f4f1e8">
  <title>${escapeHtml(title)} · AI PDLC Learning</title>
  <link rel="stylesheet" data-site-nav-styles href="./site-nav.css">
  <link rel="stylesheet" data-atmos-styles href="./atmosphere.css">
  <link rel="stylesheet" href="./help-reference.css">
</head>
<body class="reference-page">
  <a class="skip-link" href="#main-content">К содержанию</a>
  ${renderSiteNavigation({ section: 'help' })}
  <main id="main-content" class="reference-shell" tabindex="-1">
    ${body}
  </main>
</body>
</html>
`;

const roleGroups = (
  roles: readonly ReferenceRole[],
): readonly Readonly<{ label: string; roles: readonly ReferenceRole[] }>[] => {
  const groups = new Map<string, ReferenceRole[]>();
  for (const role of roles) groups.set(role.group, [...(groups.get(role.group) ?? []), role]);
  return [...groups.entries()].map(([label, groupedRoles]) => ({ label, roles: groupedRoles }));
};

const roleGroupPresentation = (label: string): Readonly<{ key: string; description: string }> =>
  label === 'Процесс'
    ? { key: 'process', description: 'Формируют, реализуют и подтверждают результат изменения.' }
    : {
        key: 'environment',
        description: 'Обеспечивают платформу, данные, безопасность и эксплуатацию.',
      };

const renderRoleCards = (roles: readonly ReferenceRole[]): string =>
  roles
    .map(
      (role) =>
        `<article class="reference-role-row reference-role-card"><header><h4>${escapeHtml(role.name)}</h4><p>${escapeHtml(role.responsibility)}</p></header><dl><div><dt>Где участвует</dt><dd>${escapeHtml(role.where)}</dd></div><div><dt>Профиль среды</dt><dd>${escapeHtml(role.environmentProfile)}</dd></div><div><dt>Разрешённые действия</dt><dd>${escapeHtml(role.allowedActions)}</dd></div><div><dt>Что подтверждает</dt><dd>${escapeHtml(role.confirms)}</dd></div><div class="reference-role-card__evidence"><dt>Чем фиксируется результат</dt><dd>${escapeHtml(role.evidence)}</dd></div></dl></article>`,
    )
    .join('');

const renderReferenceSources = (sources: readonly ReferenceSource[]): string =>
  `<aside class="reference-links" aria-label="Выборочные источники для терминов"><strong>Выборочные источники</strong><div>${sources.map((source) => `<a href="${escapeHtml(source.url)}" target="_blank" rel="noopener noreferrer">${escapeHtml(source.label)}&nbsp;↗</a>`).join('')}</div></aside>`;

const rolesDocument = (roles: readonly ReferenceRole[]): string => {
  const groups = roleGroups(roles);
  return referenceDocument(
    'Роли и зоны ответственности',
    'Полный справочник ролей и зон ответственности для материалов курса AI PDLC Learning.',
    `<header class="reference-intro">
      <p class="reference-kicker">Справка · ответственность</p>
      <h1>Роли и зоны ответственности</h1>
      <p>Кто участвует в работе, что подтверждает и каким артефактом фиксируется результат.</p>
    </header>
    ${roleSchemaPanels()}
    <section class="reference-section reference-section--roles" aria-labelledby="roles-table-title">
      <div class="reference-section__heading"><div><p class="reference-section__eyebrow">Карта ответственности</p><h2 id="roles-table-title">${roles.length} ролей в двух контурах</h2></div><p>Сначала найдите контур, затем роль и её подтверждение результата.</p></div>
      <nav class="reference-role-index" aria-label="Контуры ролей">${groups
        .map((group) => {
          const presentation = roleGroupPresentation(group.label);
          return `<a href="#role-group-${presentation.key}"><span>${escapeHtml(group.label)}</span><small>${group.roles.length} ролей · ${escapeHtml(presentation.description)}</small></a>`;
        })
        .join('')}</nav>
      <div class="reference-role-list" role="group" aria-label="Роли и зоны ответственности">
        ${groups
          .map((group) => {
            const presentation = roleGroupPresentation(group.label);
            return `<section id="role-group-${presentation.key}" class="reference-role-group" aria-labelledby="role-group-${presentation.key}-title"><header><div><h3 id="role-group-${presentation.key}-title">${escapeHtml(group.label)}</h3><p>${escapeHtml(presentation.description)}</p></div><span>${group.roles.length} ролей</span></header><div class="reference-role-grid">${renderRoleCards(group.roles)}</div></section>`;
          })
          .join('')}
      </div>
    </section>
    ${roleTeamPanels()}`,
  );
};

const glossaryDocument = (
  glossaryGroups: readonly ReferenceGlossaryGroup[],
  sources: readonly ReferenceSource[],
): string =>
  referenceDocument(
    'Глоссарий',
    'Полный глоссарий терминов и сокращений для материалов курса AI PDLC Learning.',
    `<header class="reference-intro">
      <p class="reference-kicker">Справка · термины</p>
      <h1>Глоссарий</h1>
      <p>Единые определения терминов и сокращений из карт, материалов процесса и учебного маршрута.</p>
    </header>
    <section class="reference-section reference-section--glossary" aria-labelledby="glossary-table-title">
      <div class="reference-section__heading"><div><p class="reference-section__eyebrow">Справочник</p><h2 id="glossary-table-title">${termCount(glossaryGroups.reduce((total, group) => total + group.entries.length, 0))} в ${sectionCount(glossaryGroups.length)}</h2></div><p>Выберите раздел или читайте определения последовательно.</p></div>
      <nav class="reference-group-index" aria-label="Разделы глоссария">${glossaryGroups.map((group) => `<a href="#glossary-group-${escapeHtml(group.key)}"><span>${escapeHtml(group.label)}</span><small>${termCount(group.entries.length)}</small></a>`).join('')}</nav>
      ${renderReferenceSources(sources)}
      <div class="reference-glossary-list" role="group" aria-label="Термины и определения">
        ${glossaryGroups.map((group) => `<section id="glossary-group-${escapeHtml(group.key)}" class="reference-glossary-group" aria-labelledby="glossary-group-${escapeHtml(group.key)}-title"><header><div><h3 id="glossary-group-${escapeHtml(group.key)}-title">${escapeHtml(group.label)}</h3><p>${escapeHtml(group.description)}</p></div><span>${termCount(group.entries.length)}</span></header><dl>${group.entries.map((entry) => `<div class="reference-glossary-row"><dt>${escapeHtml(entry.term)}</dt><dd>${escapeHtml(entry.definition)}</dd></div>`).join('')}</dl></section>`).join('')}
      </div>
    </section>`,
  );

/** «в пяти разделах»: the section count of the glossary heading, in the prepositional case. */
const sectionCount = (count: number): string => {
  const words = [
    'одном разделе',
    'двух разделах',
    'трёх разделах',
    'четырёх разделах',
    'пяти разделах',
    'шести разделах',
    'семи разделах',
    'восьми разделах',
    'девяти разделах',
  ];
  const word = words[count - 1];
  if (!word) throw new Error(`The glossary heading names 1-9 sections, not ${count}`);
  return word;
};

export const buildHelpReferencePages = async (
  directory = pages,
  catalog: HelpReferenceCatalog = helpReferenceCatalog,
): Promise<void> => {
  validateHelpReferenceCatalog(catalog);
  const roles = rolesDocument(catalog.roles);
  const glossary = glossaryDocument(catalog.glossaryGroups, catalog.sources);
  await Promise.all([
    writeFile(resolve(directory, 'roles.html'), roles),
    writeFile(resolve(directory, 'glossary.html'), glossary),
  ]);
};

if (import.meta.main) await buildHelpReferencePages();
