#!/usr/bin/env node
// План звуковых событий ролика «Обзор главной страницы v4» (6 сцен) → sfx.json (формат sfx-plan.ts: явный список events).
//   node tools/make-sfx.mjs          пишет sfx.json
// Время события = старт сцены (scenes.json) + момент в озвучке (alignment) + смещение — те же числа, что в work/scenes/NN.js.
// Эффекты (video/_shared/sfx): swipe — смена сцены и движение камеры; pop — появление кольца, выноски, значка;
// click — нажатие кнопки; subdrop — выход из заставки и хвост ролика.
import { readFileSync, writeFileSync } from "node:fs";
const fs = await import("node:fs");
const path = await import("node:path");
const { dirname, resolve } = path;
const { fileURLToPath } = await import("node:url");
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scenes = JSON.parse(readFileSync(`${root}/scenes.json`, "utf8"));
const al = scenes.map((s) => JSON.parse(readFileSync(`${root}/assets/vo/scene-${String(s.n).padStart(2, "0")}.alignment.json`, "utf8")));
const starts = scenes.reduce((a, s) => (a.push(a.at(-1) + s.duration), a), [0]);
const norm = (s) => s.toLowerCase().replace(/ё/g, "е");
// время первого (или n-го) вхождения фразы в реплику сцены; фразы нет — ошибка плана
const T = (n, phrase, nth = 1) => {
  const a = al[n - 1], text = a.characters.join("");
  let from = 0, idx = -1;
  for (let i = 0; i < nth; i++) {
    idx = text.indexOf(phrase, from);
    if (idx < 0) idx = norm(text).indexOf(norm(phrase), from);
    if (idx < 0) throw new Error(`сцена ${n}: нет фразы «${phrase}» (${nth})`);
    from = idx + 1;
  }
  return a.character_start_times_seconds[idx];
};
const ev = [];
const e = (n, t, kind, pan, note) => ev.push({ kind, t: Number((starts[n - 1] + t).toFixed(3)), pan, note: `${n}: ${note}` });
const t = T;
// --- сцена 1: светлая заставка → H1 страницы, спуск камеры к карте
e(1, 1.45, "subdrop", 0, "выход из светлой заставки");
e(1, 2.0, "pop", -0.4, "прожектор на блоке H1");
e(1, t(1, "обзор") + 0.1, "pop", -0.4, "выноска «Главная страница»");
e(1, t(1, "маршрут"), "pop", -0.3, "выноска «Один маршрут»");
e(1, t(1, "намерения") + 0.1, "pop", 0.2, "выноска «От намерения»");
e(1, t(1, "работающего"), "pop", 0.3, "выноска «До результата»");
e(1, t(1, "результата") + 0.1, "swipe", 0.4, "спуск камеры к карте");
// --- сцена 2: карта PDLC
e(2, 0, "swipe", 0, "смена сцены 2");
e(2, t(2, "карта") - 0.2, "pop", 0.4, "выноска «Карта PDLC»");
e(2, t(2, "Семь"), "pop", 0.3, "выноска «7 этапов»");
e(2, t(2, "Семь") + 0.35, "pop", 0.1, "волна узлов 01–03");
e(2, t(2, "Семь") + 0.7, "pop", -0.1, "волна узлов 04–05");
e(2, t(2, "Семь") + 1.05, "pop", -0.3, "волна узлов 06–07");
e(2, t(2, "намерения"), "pop", 0.2, "кольцо «Намерение», выноска");
e(2, t(2, "наблюдения"), "pop", 0.3, "кольцо «Наблюдение», выноска");
e(2, t(2, "агент готовит"), "pop", 0.2, "строка «Агент готовит»");
e(2, t(2, "человек решает"), "pop", 0.3, "строка «Человек решает»");
e(2, t(2, "результат"), "pop", 0.1, "выноска «Результат»");
e(2, t(2, "намерение,"), "pop", 0.1, "тег результата 01");
e(2, t(2, "требования,"), "pop", 0.1, "тег результата 02");
e(2, t(2, "решение"), "pop", 0.1, "тег результата 03");
e(2, t(2, "изменение"), "pop", 0.1, "тег результата 04");
e(2, t(2, "тесты,"), "pop", 0.1, "тег результата 05");
e(2, t(2, "выпуск"), "pop", 0.1, "тег результата 06");
e(2, t(2, "метрики."), "pop", 0.1, "тег результата 07");
e(2, t(2, "Курсы уже"), "pop", -0.4, "выноска «Есть курс»");
e(2, t(2, "остальные"), "pop", -0.2, "выноска «В работе»");
// --- сцена 3: как встроить ИИ
e(3, 0, "swipe", -0.4, "смена сцены 3, камера к карточкам");
e(3, t(3, "«Как") - 0.1, "pop", 0.4, "кольцо и выноска «Как встроить ИИ»");
e(3, t(3, "место человека"), "pop", -0.3, "строка «Человек и агент»");
e(3, t(3, "почему"), "pop", 0.3, "строка «Репозиторий»");
e(3, t(3, "с чего"), "pop", 0.2, "строка «С чего начать»");
e(3, t(3, "гайде"), "pop", -0.2, "кольцо на ссылке «Гайд «Проблемы и цель»»");
// --- сцена 4: команда развития
e(4, 0, "swipe", 0.4, "смена сцены 4");
e(4, t(4, "команда"), "pop", 0.1, "кольцо на заголовке правой карточки");
e(4, t(4, "формирует"), "pop", 0.1, "строка «Метод»");
e(4, t(4, "шаг за шагом"), "pop", 0.3, "строка «Шаг за шагом»");
e(4, t(4, "аудит,"), "pop", 0.2, "строка «Аудит → метрики»");
e(4, t(4, "метрики."), "click", -0.2, "кольцо на кнопке «Пройти аудит»");
// --- сцена 5: разделы страницы
e(5, 0, "swipe", 0.5, "смена сцены 5, камера к секциям");
e(5, t(5, "Намерение") - 0.05, "pop", 0.2, "выноска «Намерение и план»");
e(5, t(5, "Анализ") - 0.7, "swipe", 0.2, "переезд камеры к «Анализу»");
e(5, t(5, "Анализ"), "pop", 0.1, "выноска «Анализ»");
e(5, t(5, "гайды"), "pop", 0.1, "выноска «Гайды и курсы»");
e(5, t(5, "Среда") - 0.7, "swipe", -0.4, "переезд камеры к «Среде и контурам»");
e(5, t(5, "Среда"), "pop", -0.4, "выноска «Среда и контуры»");
e(5, t(5, "границы"), "pop", 0.4, "выноска «Границы среды»");
e(5, t(5, "Внизу") - 0.7, "swipe", -0.3, "переезд камеры к «Справке»");
e(5, t(5, "Внизу"), "pop", 0.3, "выноска «Справка»");
e(5, t(5, "всех"), "pop", 0.2, "выноска «Для всех ролей»");
e(5, t(5, "Где") + 0.1, "pop", 0.2, "выноска «В работе»");
// --- сцена 6: концовка, обратный проход к карте → кнопка «Пройти аудит»
e(6, 0.2, "swipe", 0.5, "подъём камеры к карте");
e(6, 1.7, "pop", 0, "выноска «Найдите свой этап», узел 01 пульсирует");
e(6, t(6, "Нужна"), "swipe", -0.3, "переезд камеры к карточке команды");
e(6, t(6, "начните") + 0.2, "click", -0.2, "кольцо на кнопке «Пройти аудит»");
const total = starts.at(-1);
ev.push({ kind: "subdrop", t: Number((total - 2.3).toFixed(3)), pan: 0, note: "6: хвост — выход из ролика" });
ev.sort((a, b) => a.t - b.t);
// событие того же вида ближе 0,25 с к предыдущему сливается в один удар: убираем его и пишем в журнал
for (let i = ev.length - 1; i > 0; i--) {
  const p = ev.slice(0, i).reverse().find((q) => q.kind === ev[i].kind);
  if (p && ev[i].t - p.t < 0.25) { console.log(`пропуск: ${ev[i].note} (${String(ev[i].t)}) близко к ${p.note}`); ev.splice(i, 1); }
}
writeFileSync(`${root}/sfx.json`, JSON.stringify({ events: ev }, null, 1) + "\n");
console.log(`sfx.json: ${ev.length} событий (swipe ${ev.filter((x) => x.kind === "swipe").length}, pop ${ev.filter((x) => x.kind === "pop").length}, click ${ev.filter((x) => x.kind === "click").length}, subdrop ${ev.filter((x) => x.kind === "subdrop").length})`);
