#!/usr/bin/env node
// План звуковых событий ролика → sfx.json (формат sfx-plan.ts: явный список events).
//   node tools/make-sfx.mjs          пишет sfx.json
// Время события = старт сцены (scenes.json) + момент в озвучке (alignment) + смещение — те же числа, что в work/scenes/NN.js.
// Эффекты (video/_shared/sfx): swipe — смена сцены и движение линии; pop — появление блока, заголовка, фигуры; click — нажатие; subdrop — выход из заставки и хвост.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const scenes = JSON.parse(readFileSync(`${root}/scenes.json`, "utf8"));
const al = scenes.map((s) => JSON.parse(readFileSync(`${root}/assets/vo/scene-${String(s.n).padStart(2, "0")}.alignment.json`, "utf8")));
const starts = scenes.reduce((a, s) => (a.push(a.at(-1) + s.duration), a), [0]);
const norm = (s) => s.toLowerCase().replace(/ё/g, "е");
const T = (n, phrase, nth = 1) => {
  const a = al[n - 1], text = a.characters.join("");
  let from = 0, idx = -1;
  for (let i = 0; i < nth; i++) {
    idx = text.indexOf(phrase, from);
    if (idx < 0) idx = norm(text).indexOf(norm(phrase), from);
    if (idx < 0) throw new Error(`сцена ${n}: нет фразы «${phrase}» (${nth})`);
    from = idx + 1;
  }
  return a.character_start_times_seconds[idx];
};
const ev = [];
// e(сцена, секунды в сцене, вид, панорама, пометка)
const e = (n, t, kind, pan, note) => ev.push({ kind, t: Number((starts[n - 1] + t).toFixed(3)), pan, note: `${n}: ${note}` });
const t = T;
// --- сцены 1–4 и 9 (прежняя «Команда развития») не менялись: события берутся из опубликованного мастера (sfx-published.json), у сцены 9 со сдвигом на новый старт
const PUBLISHED = JSON.parse(readFileSync(`${root}/sfx-published.json`, "utf8")).events;
const oldStart = [0, 21.7, 46.2, 84.8, 108.2, 136.1, 168.2, 195.3]; // старты сцен в опубликованном мастере (227,7 с)
for (const [nn, on] of [[1, 1], [2, 2], [3, 3], [4, 4], [9, 7]]) {
  for (const p of PUBLISHED.filter((x) => x.note.startsWith(`${on}:`)))
    ev.push({ ...p, t: Number((p.t - oldStart[on - 1] + starts[nn - 1]).toFixed(3)), note: p.note.replace(`${on}:`, `${nn}:`) });
}
// --- сцена 5
e(5, 0, "swipe", -0.5, "смена сцены 5");
e(5, t(5, "репозиторий") - 0.1, "pop", 0.5, "папка репозитория");
e(5, t(5, "намерение,"), "pop", 0.4, "файлы репозитория");
e(5, t(5, "Внешние системы"), "pop", -0.5, "плашка «внешние системы»");
e(5, t(5, "основа"), "pop", 0.5, "значок «основа»");
e(5, t(5, "Одна") - 0.5, "swipe", 0, "переход к спецификации");
e(5, t(5, "Одна") + 0.1, "pop", -0.5, "spec.md");
e(5, t(5, "запросе"), "pop", 0.4, "нить к запросу на слияние");
e(5, t(5, "тестах"), "pop", 0.4, "нить к тестам");
e(5, t(5, "решении"), "pop", 0.4, "нить к решению об архитектуре");
e(5, t(5, "Кто"), "swipe", 0, "линейка коммитов");
e(5, t(5, "чьей-то"), "pop", 0.3, "чья-то память");
// --- сцена 6
e(6, 0, "swipe", 0.5, "смена сцены 6");
e(6, 0.5, "pop", -0.5, "карта этапов");
e(6, t(6, "что делает человек"), "pop", -0.3, "строка «что делает человек»");
e(6, t(6, "что готовит агент"), "pop", 0.3, "строка «что готовит агент»");
e(6, t(6, "открывают"), "pop", -0.4, "кнопка «Курс →» у этапа 01");
e(6, t(6, "открывают") + 0.2, "pop", -0.3, "кнопка «Курс →» у этапа 02");
e(6, t(6, "остальные"), "pop", 0.3, "«Курс в работе» у остальных этапов");
e(6, t(6, "Подготовка") - 0.55, "swipe", 0, "от карты к курсу");
e(6, t(6, "Подготовка") - 0.3, "pop", 0, "полоса курса");
e(6, t(6, "мета-репозиторий") + 0.3, "pop", -0.4, "схема мета-репозитория");
e(6, t(6, "практика") + 0.1, "swipe", 0.3, "эстафета практики");
e(6, t(6, "В каждом"), "pop", -0.4, "карточка шага");
// --- сцена 7: среда и контуры
e(7, 0, "swipe", -0.5, "смена сцены 7");
e(7, 0.4, "pop", 0, "заголовок раздела");
e(7, t(7, "шкалы") - 0.1, "pop", -0.5, "карточка «Шкалы зрелости»");
e(7, t(7, "контуры,") - 0.1, "pop", 0.4, "карточка «Контуры»");
e(7, t(7, "логи") - 0.1, "pop", -0.4, "карточка «Логи через Grafana»");
e(7, t(7, "обоснование") - 0.1, "pop", 0.5, "карточка «Обоснование среды»");
e(7, t(7, "Логи и обоснование"), "pop", 0, "два материала по коду доступа");
// --- сцена 8: команды и поддержка
e(8, 0, "swipe", 0.5, "смена сцены 8");
e(8, 0.4, "pop", 0, "заголовок раздела");
e(8, t(8, "два материала") - 0.2, "pop", -0.5, "карточка «Атлас команд»");
e(8, t(8, "два материала") + 0.3, "pop", 0.5, "карточка «Поддержка продуктов»");
e(8, t(8, "оба"), "pop", 0, "по коду доступа");
// --- сцена 10: справка и роли
e(10, 0, "swipe", 0.5, "смена сцены 10");
e(10, t(10, "Аналитик") - 0.15, "pop", -0.5, "аналитик");
e(10, t(10, "Владелец продукта") - 0.15, "pop", -0.3, "владелец продукта");
e(10, t(10, "Архитектор") - 0.15, "pop", -0.2, "архитектор");
e(10, t(10, "технический лидер") - 0.15, "pop", 0, "технический лидер");
e(10, t(10, "Разработчик") - 0.15, "pop", 0.1, "разработчик");
e(10, t(10, "инженер качества") - 0.15, "pop", 0.3, "инженер качества");
e(10, t(10, "эксплуатация") - 0.15, "pop", 0.5, "эксплуатация");
e(10, t(10, "Руководителю") - 0.1, "pop", 0.5, "руководитель");
e(10, t(10, "А общее") - 0.4, "swipe", 0, "переход к справке");
e(10, t(10, "гайд «Маркдаун") - 0.15, "pop", -0.4, "карточка «Markdown, Git»");
e(10, t(10, "роли и зоны") - 0.15, "pop", 0.4, "карточка «Роли»");
e(10, t(10, "глоссарий") - 0.15, "pop", -0.4, "карточка «Глоссарий»");
e(10, t(10, "ресурсы") - 0.15, "pop", 0.4, "карточка «Ресурсы»");
e(10, t(10, "Начните") - 0.4, "swipe", 0, "переход к кнопкам");
e(10, t(10, "Начните") + 0.3, "pop", -0.4, "кнопка «Карта этапов»");
e(10, t(10, "Начните") + 0.7, "pop", 0, "кнопка «Курс анализа»");
e(10, t(10, "Начните") + 1.1, "pop", 0.4, "кнопка «Аудит продукта»");
const total = starts.at(-1);
e(10, scenes.at(-1).duration - 1.5, "click", -0.2, "тихий click по первой кнопке");
ev.push({ kind: "subdrop", t: Number((total - 2.3).toFixed(3)), pan: 0, note: "10: хвост — выход из ролика" });
ev.sort((a, b) => a.t - b.t);
// два события одного вида ближе 0,25 с — ошибка плана (слипнутся в один удар)
// событие того же вида ближе 0,25 с к предыдущему сливается в один удар: убираем его и пишем в журнал
for (let i = ev.length - 1; i > 0; i--) { const p = ev.slice(0, i).reverse().find((q) => q.kind === ev[i].kind); if (p && ev[i].t - p.t < 0.25) { console.log(`пропуск: ${ev[i].note} (${ev[i].t}) близко к ${p.note}`); ev.splice(i, 1); } }
writeFileSync(`${root}/sfx.json`, JSON.stringify({ events: ev }, null, 1) + "\n");
console.log(`sfx.json: ${ev.length} событий (swipe ${ev.filter((x) => x.kind === "swipe").length}, pop ${ev.filter((x) => x.kind === "pop").length}, click ${ev.filter((x) => x.kind === "click").length}, subdrop ${ev.filter((x) => x.kind === "subdrop").length})`);
